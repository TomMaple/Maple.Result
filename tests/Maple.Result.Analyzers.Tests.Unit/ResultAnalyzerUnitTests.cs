using Maple.Results.Analyzers.Tests.Unit.TestingInfrastructure.Helpers;
using Microsoft.CodeAnalysis;
using System;
using System.Linq;

namespace Maple.Results.Analyzers.Tests.Unit;

/// <summary>
///     Tests of what the analyzers share (<see cref="ResultAnalyzer" />): the rules that replace a compile error of the library cannot be
///     switched off by a pragma or by the compilation options and are reported in generated code, the warnings can and are not; and nothing
///     is analyzed in a compilation that does not reference the library.
/// </summary>
public class ResultAnalyzerUnitTests
{
    private const string GeneratedSource = """
        // <auto-generated />
        using System.Threading.Tasks;
        using Maple.Results;
        using Maple.Results.Extensions;

        public static class Generated
        {
            static Result<int> Load() => 1;
            static Task SaveAsync() => Task.CompletedTask;

            static void Run()
            {
                STATEMENT
            }
        }
        """;

    private const string SourceWithoutTheLibrary = """
        using System;
        using System.Collections.Generic;
        using System.Threading.Tasks;

        public static class Snippet
        {
            static Task SaveAsync() => Task.CompletedTask;

            static void Run()
            {
                new List<int> { 1 }.ForEach(x => SaveAsync());
                SaveAsync();
            }
        }
        """;

    [Theory]
    [InlineData(Rules.InferredResultValueId, "var r = ok.Then(x => GetIntAsync());")]
    [InlineData(Rules.UnawaitedTaskId, "_ = ok.IfSuccess(x => SaveAsync());")]
    [InlineData(Rules.ConvertedResultValueId, "Result<object> r = SaveAsync();")]
    [InlineData(Rules.DroppedResultId, "_ = ok.IfSuccess(x => GetResultOfInt());")]
    public void Analyze_ErrorRuleDisabledByAPragma_StillReportsIt(string id, string statement)
    {
        // Arrange
        var statements = $"#pragma warning disable {id}\n{statement}\n#pragma warning restore {id}";

        // Act
        var result = AnalyzerRunner.Run(statements, members: "", AnalyzerRunner.AllAnalyzers);

        // Assert
        result.CompilerErrorIds.ShouldBeEmpty(result.CompilerErrors);
        var diagnostic = result.Diagnostics.ShouldHaveSingleItem();
        diagnostic.Id.ShouldBe(id);
        diagnostic.Severity.ShouldBe(DiagnosticSeverity.Error);
    }

    [Theory]
    [InlineData(Rules.IgnoredValueId, "var r = ok.IfSuccess(x => Compute());")]
    [InlineData(Rules.DiscardedResultId, "GetResult();")]
    public void Analyze_WarningRuleDisabledByAPragma_ReportsNothing(string id, string statement)
    {
        // Arrange
        var statements = $"#pragma warning disable {id}\n{statement}\n#pragma warning restore {id}";

        // Act
        var result = AnalyzerRunner.Run(statements, members: "", AnalyzerRunner.AllAnalyzers);

        // Assert
        result.CompilerErrorIds.ShouldBeEmpty(result.CompilerErrors);
        result.DiagnosticIds.ShouldBeEmpty();
    }

    [Theory]
    [InlineData(Rules.InferredResultValueId, "var r = Load().Then(x => SaveAsync());")]
    [InlineData(Rules.UnawaitedTaskId, "_ = Load().IfSuccess(x => SaveAsync());")]
    [InlineData(Rules.ConvertedResultValueId, "Result<object> r = SaveAsync();")]
    [InlineData(Rules.DroppedResultId, "_ = Load().IfSuccess(x => Load());")]
    public void Analyze_ErrorRuleSuppressedByTheCompilationOptions_StillReportsIt(string id, string statement)
    {
        // Arrange
        var source = GeneratedSource.Replace("// <auto-generated />", "").Replace("STATEMENT", statement);

        // Act
        var result = AnalyzerRunner.RunSource(source, AnalyzerRunner.AllAnalyzers, referenceLibrary: true, id);

        // Assert
        result.CompilerErrorIds.ShouldBeEmpty(result.CompilerErrors);
        result.DiagnosticIds.ShouldBe([id]);
    }

    [Theory]
    [InlineData(Rules.IgnoredValueId, "var r = Load().IfSuccess(x => x.CompareTo(0));")]
    [InlineData(Rules.DiscardedResultId, "Load();")]
    public void Analyze_WarningRuleSuppressedByTheCompilationOptions_ReportsNothing(string id, string statement)
    {
        // Arrange
        var source = GeneratedSource.Replace("// <auto-generated />", "").Replace("STATEMENT", statement);

        // Act
        var result = AnalyzerRunner.RunSource(source, AnalyzerRunner.AllAnalyzers, referenceLibrary: true, id);

        // Assert
        result.CompilerErrorIds.ShouldBeEmpty(result.CompilerErrors);
        result.DiagnosticIds.ShouldBeEmpty();
    }

    [Theory]
    [InlineData(Rules.InferredResultValueId, "var r = Load().Then(x => SaveAsync());")]
    [InlineData(Rules.UnawaitedTaskId, "_ = Load().IfSuccess(x => SaveAsync());")]
    [InlineData(Rules.ConvertedResultValueId, "Result<object> r = SaveAsync();")]
    [InlineData(Rules.DroppedResultId, "_ = Load().IfSuccess(x => Load());")]
    public void Analyze_ErrorRuleInGeneratedCode_ReportsIt(string id, string statement)
    {
        // Arrange
        var source = GeneratedSource.Replace("STATEMENT", statement);

        // Act
        var result = AnalyzerRunner.RunSource(source, AnalyzerRunner.AllAnalyzers);

        // Assert
        result.CompilerErrorIds.ShouldBeEmpty(result.CompilerErrors);
        result.DiagnosticIds.ShouldBe([id]);
    }

    [Theory]
    [InlineData("var r = Load().IfSuccess(x => x.CompareTo(0));")]
    [InlineData("Load();")]
    public void Analyze_WarningRuleInGeneratedCode_ReportsNothing(string statement)
    {
        // Arrange
        var source = GeneratedSource.Replace("STATEMENT", statement);

        // Act
        var result = AnalyzerRunner.RunSource(source, AnalyzerRunner.AllAnalyzers);

        // Assert
        result.CompilerErrorIds.ShouldBeEmpty(result.CompilerErrors);
        result.DiagnosticIds.ShouldBeEmpty();
    }

    [Fact]
    public void Analyze_CompilationWithoutTheLibrary_ReportsNothing()
    {
        // Act
        var result = AnalyzerRunner.RunSource(SourceWithoutTheLibrary, AnalyzerRunner.AllAnalyzers, referenceLibrary: false);

        // Assert
        result.CompilerErrorIds.ShouldBeEmpty(result.CompilerErrors);
        result.DiagnosticIds.ShouldBeEmpty();
    }

    [Theory]
    [InlineData(Rules.InferredResultValueId)]
    [InlineData(Rules.UnawaitedTaskId)]
    [InlineData(Rules.ConvertedResultValueId)]
    [InlineData(Rules.DroppedResultId)]
    public void SupportedDiagnostics_ErrorRule_IsNotConfigurable(string id)
    {
        // Act
        var descriptor = AnalyzerRunner.AllAnalyzers.SelectMany(a => a.SupportedDiagnostics).Single(d => d.Id == id);

        // Assert
        descriptor.DefaultSeverity.ShouldBe(DiagnosticSeverity.Error);
        descriptor.CustomTags.ShouldContain(WellKnownDiagnosticTags.NotConfigurable);
    }

    [Theory]
    [InlineData(Rules.IgnoredValueId)]
    [InlineData(Rules.DiscardedResultId)]
    public void SupportedDiagnostics_WarningRule_IsConfigurable(string id)
    {
        // Act
        var descriptor = AnalyzerRunner.AllAnalyzers.SelectMany(a => a.SupportedDiagnostics).Single(d => d.Id == id);

        // Assert
        descriptor.DefaultSeverity.ShouldBe(DiagnosticSeverity.Warning);
        descriptor.CustomTags.ShouldNotContain(WellKnownDiagnosticTags.NotConfigurable);
    }

    [Fact]
    public void SupportedDiagnostics_EveryRule_HasAHelpLinkToItsPage()
    {
        // Arrange
        // The documentation at the git reference of the build: main, or the tag of the release that the Publish workflow builds and tests.
        var expectedStart = "https://github.com/TomMaple/Maple.Result/blob/" + Rules.HelpLinkRef + "/docs/Analyzers/";

        // Act
        var links = AnalyzerRunner.AllAnalyzers
            .SelectMany(a => a.SupportedDiagnostics)
            .Select(d => d.HelpLinkUri)
            .Order(StringComparer.Ordinal)
            .ToArray();

        // Assert
        links.ShouldBe(
        [
            expectedStart + "MR0001.md",
            expectedStart + "MR0002.md",
            expectedStart + "MR0003.md",
            expectedStart + "MR0004.md",
            expectedStart + "MR0005.md",
            expectedStart + "MR0006.md",
        ]);
    }

    [Fact]
    public void HelpLinkRef_Always_IsMainOrTheTagOfARelease()
    {
        // Act
        var reference = Rules.HelpLinkRef;

        // Assert
        reference.ShouldMatch(@"^(main|v\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?)$");
    }
}
